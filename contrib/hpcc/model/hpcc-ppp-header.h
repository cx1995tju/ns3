#ifndef HPCC_PPP_HEADER_H
#define HPCC_PPP_HEADER_H

#include "ns3/ppp-header.h"

namespace ns3
{
/// Protocol field followed by the twelve padding bytes counted by the HPCC simulator.
class HpccPppHeader : public PppHeader
{
  public:
    static constexpr uint32_t GetStaticSize()
    {
        return 14;
    }

    static TypeId GetTypeId();
    TypeId GetInstanceTypeId() const override;
    uint32_t GetSerializedSize() const override;
    void Serialize(Buffer::Iterator start) const override;
    uint32_t Deserialize(Buffer::Iterator start) override;
};
} // namespace ns3
#endif
